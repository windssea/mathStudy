const root = fileURLToPath(new URL('../../', import.meta.url));
const output: Question[] = [];
const topics: { id: string; unitId: string; title: string }[] = [];
let current: { id: string; unit: number; lesson: string; pages: [number, number] };
function topic(id: string, title: string, unit: number, lesson: string, pages: [number, number]) {
  current = { id, unit, lesson, pages };
  topics.push({ id, unitId: 'U0' + unit, title });
}
type Spec = {
  lesson?: string;
  pages?: [number, number];
  title: string;
  stem: string;
  type?: QuestionType;
  difficulty?: Difficulty;
  answers: (string | number)[];
  labels: string[];
  suffixes?: string[];
  analysis: string;
  steps: string[];
  pitfall: string;
  scenes?: Scene[];
  options?: string[];
  rules?: Question['answerRules'];
};
function q(serial: number, s: Spec) {
  const id = 'bank-' + current.id + '-' + String(serial).padStart(2, '0');
  const fieldKey = (index: number) => (s.options ? 'value' : 'a' + (index + 1));
  if (s.scenes && s.scenes.length !== s.steps.length) throw new Error('Stage mismatch: ' + id);
  const stages = s.scenes?.map((scene, index) => {
    const filename = id + '-step' + (index + 1) + '.svg';
    writeFileSync(root + 'apps/web/public/figures/' + filename, renderScene(scene));
    return { kind: 'image' as const, image: '/figures/' + filename, headings: [], rows: [] };
  });
  const question = questionSchema.parse({
    id,
    unitId: 'U0' + current.unit,
    lessonId: s.lesson ?? current.lesson,
    topicIds: [current.id],
    title: s.title,
    stem: s.stem,
    type: s.type ?? 'application',
    difficulty: s.difficulty ?? 'advanced',
    fields: s.answers.map((answer, i) => ({
      key: fieldKey(i),
      label: s.labels[i],
      suffix: s.suffixes?.[i],
      inputMode: /^\d+$/.test(String(answer)) ? 'numeric' : 'text',
    })),
    expected: Object.fromEntries(s.answers.map((answer, i) => [fieldKey(i), String(answer)])),
    sourceKind: 'original',
    pages: s.pages ?? current.pages,
    knowledge: topics.at(-1)!.title,
    hint: s.analysis,
    hasVisual: !!stages,
    options: s.options,
    answerRules: s.rules,
    explanation: {
      analysis: s.analysis,
      steps: s.steps,
      pitfall: s.pitfall,
      answer: s.options
        ? s.options[Number(s.answers[0])]
        : s.answers
            .map((answer, i) => s.labels[i] + '：' + answer + (s.suffixes?.[i] ?? ''))
            .join('；'),
      visual: stages
        ? { kind: 'reasoning', title: s.title, labels: [], values: [], captions: s.steps, stages }
        : undefined,
    },
  });
  if (question.difficulty === 'challenge' && !stages)
    throw new Error('Challenge needs artwork: ' + id);
  output.push(question);
}
const parts = (
  title: string,
  rows: { label: string; parts: [string, number][] }[],
  note: string,
): Scene => ({ kind: 'parts', title, rows, note });
const row = (label: string, ...parts: [string, number][]) => ({ label, parts });
const table = (
  title: string,
  headings: string[],
  rows: string[][],
  note: string,
  active?: number,
): Scene => ({ kind: 'table', title, headings, rows, note, active });
const digits = (title: string, numbers: string[], note: string, highlights?: number[]): Scene => ({
  kind: 'digits',
  title,
  numbers,
  note,
  highlights,
});
const range = (
  title: string,
  lower: number,
  upper: number,
  note: string,
  selected?: [number, number],
): Scene => ({ kind: 'range', title, lower, upper, note, selected });
