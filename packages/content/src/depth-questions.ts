import type { Question, Visual, Difficulty } from '@mathstudy/contracts';

type Stage = NonNullable<Visual['stages']>[number];
const table = (headings: string[], rows: string[][], highlights: number[] = []): Stage => ({
  kind: 'table',
  headings,
  rows,
  highlights,
});
const flow = (rows: string[][]): Stage => ({ kind: 'flow', headings: [], rows });
const bars = (labels: string[], values: number[], rows: string[][]): Stage => ({
  kind: 'bars',
  headings: labels,
  values,
  rows,
});
const digits = (value: string, highlights: number[]): Stage => ({
  kind: 'digits',
  headings: ['十万', '万', '千', '百', '十', '个'],
  rows: [value.split('')],
  highlights,
});
function make(
  unit: number,
  serial: number,
  lesson: string | undefined,
  title: string,
  stem: string,
  answer: number,
  suffix: string,
  difficulty: Difficulty,
  analysis: string,
  steps: string[],
  stages: Stage[],
  pitfall: string,
  type: Question['type'] = 'application',
): Question {
  const visual: Visual = {
    kind: 'reasoning',
    title,
    labels: [],
    values: [],
    captions: steps,
    stages,
  };
  return {
    id: `u${unit}-${serial}`,
    unitId: `U0${unit}`,
    lessonId: lesson,
    title,
    stem,
    type,
    difficulty,
    fields: [{ key: 'value', label: type === 'fill' ? '填入的数' : '你的答案', suffix }],
    hint: analysis,
    sourceKind: 'original',
    knowledge: title,
    pages: (
      { 1: [2, 16], 2: [18, 43], 3: [45, 56], 4: [58, 63], 5: [68, 88], 6: [95, 103] } as Record<
        number,
        [number, number]
      >
    )[unit],
    hasVisual: true,
    expected: { value: String(answer) },
    explanation: { analysis, steps, answer: `${answer}${suffix}`, pitfall, visual },
  };
}

