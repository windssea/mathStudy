import type { Question, Visual } from '@mathstudy/contracts';

function make(
  id: string,
  title: string,
  stem: string,
  answer: number,
  suffix: string,
  analysis: string,
  steps: string[],
  difficulty: Question['difficulty'] = 'basic',
  type: Question['type'] = 'fill',
  visual?: Visual,
): Question {
  return {
    id,
    title,
    stem,
    unitId: 'U02',
    type,
    difficulty,
    fields: [{ key: 'value', label: '你的答案', suffix }],
    hint: analysis,
    sourceKind: 'original',
    knowledge: title,
    pages: [20, 43],
    hasVisual: !!visual,
    expected: { value: String(answer) },
    explanation: {
      analysis,
      steps,
      answer: `${answer}${suffix}`,
      pitfall: '分清长度与面积，记录相同单位，再检查有没有遗漏的部分。',
      visual,
    },
  };
}
